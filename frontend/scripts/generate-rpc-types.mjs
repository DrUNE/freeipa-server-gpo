// Writes types/rpc.d.ts: the TypeScript types of the `gpo_editor_*` answers, inferred from the reference answers in
// tests/contracts/gpo_editor/*.json (the same files that tests/test_gpo_editor_contract.py checks the server with).
//
//   node scripts/generate-rpc-types.mjs          rewrite the file
//   node scripts/generate-rpc-types.mjs --check  fail when the file is not up to date (tests/unit/rpc-types.test.js)
//
// `null` in a reference answer means "any value" and becomes `unknown`; arrays are typed by their first element.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const contracts = path.resolve(root, '..', 'tests', 'contracts', 'gpo_editor');
const target = path.join(root, 'types', 'rpc.d.ts');
const ENVELOPE = [
    'gpo',
    'snapshot',
    'template',
    'security_catalog_status',
    'locales',
    'diagnostics',
    'pending_publication'
];

const pascal = name => name.replace(/(^|_)(\w)/g, (_, __, letter) => letter.toUpperCase());

function typeOf(value, indent) {
    if (value === null || value === undefined) return 'unknown';
    if (Array.isArray(value)) {
        if (!value.length) return 'unknown[]';
        return `${typeOf(value[0], indent)}[]`; // elements are primitives or object literals: no parentheses needed
    }
    if (typeof value === 'object') {
        const pad = '    '.repeat(indent + 1);
        const lines = Object.entries(value).map(
            ([key, child]) => `${pad}${/^\w+$/.test(key) ? key : JSON.stringify(key)}: ${typeOf(child, indent + 1)};`
        );
        return lines.length ? `{\n${lines.join('\n')}\n${'    '.repeat(indent)}}` : 'Record<string, never>';
    }
    return typeof value;
}

export function generate() {
    const files = fs
        .readdirSync(contracts)
        .filter(name => name.endsWith('.json'))
        .sort()
        .map(name => JSON.parse(fs.readFileSync(path.join(contracts, name), 'utf8')));
    const envelope = Object.fromEntries(ENVELOPE.map(key => [key, files[0].result[key]]));
    const out = [
        '// GENERATED by scripts/generate-rpc-types.mjs from tests/contracts/gpo_editor/*.json; do not edit.',
        '// The types of the `gpo_editor_*` answers (the `result` of the JSON-RPC answer).',
        '',
        `/** The part of every answer that describes the policy and the state of its publication. */`,
        `export interface EditorEnvelope ${typeOf(envelope, 0)}`,
        ''
    ];
    for (const file of files) {
        const rest = Object.fromEntries(Object.entries(file.result).filter(([key]) => !ENVELOPE.includes(key)));
        out.push(`/** Answer of \`${file.method}\`. */`);
        out.push(`export type ${pascal(file.method)}Result = EditorEnvelope & ${typeOf(rest, 0)};`, '');
    }
    return out.join('\n');
}

if (process.argv[1] === import.meta.filename) {
    const text = generate();
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) {
            console.error('types/rpc.d.ts is not up to date: run `npm run types:rpc` and commit it.');
            process.exit(1);
        }
        console.log('types/rpc.d.ts is up to date');
    } else {
        fs.writeFileSync(target, text);
        console.log('wrote ' + path.relative(root, target));
    }
}
